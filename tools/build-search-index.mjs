// Builds interactive/assets/data/search-index.js from the lesson pages.
// Usage: node tools/build-search-index.mjs [--check]   (--check fails if the file is stale)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRegistry } from './lib/registry.mjs';

const root = resolve(fileURLToPath(new URL('../interactive', import.meta.url)));
const out = join(root, 'assets', 'data', 'search-index.js');
const decode = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&#?\w+;/g, ' ');
const text = (h) => decode(h.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();

const entries = [];
for (const f of loadRegistry().lessons.map((l) => l.file)) {
  const html = readFileSync(join(root, f), 'utf8');
  const title = text((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [, f])[1]);
  const main = (html.match(/<main[^>]*>([\s\S]*)<\/main>/) || [, ''])[1];
  [...main.matchAll(/<section([^>]*)>([\s\S]*?)<\/section>/g)].forEach((m, i) => {
    const id = (m[1].match(/\sid="([^"]+)"/) || [, 's' + (i + 1)])[1];
    const h = text((m[2].match(/<h2[^>]*>([\s\S]*?)<\/h2>/) || [, 'Section ' + (i + 1)])[1]);
    entries.push({ f, n: title, id, h, x: text(m[2]).slice(0, 6000) });
  });
}
const body = '/* Generated by tools/build-search-index.mjs. Do not edit. */\nCT.searchIndex = ' + JSON.stringify(entries) + ';\n';
if (process.argv.includes('--check')) {
  // Compare with LF endings: a Windows checkout may have converted the file to CRLF.
  if (!existsSync(out) || readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== body) { console.error('search-index.js is stale: run node tools/build-search-index.mjs'); process.exit(1); }
  console.log('search index is up to date');
} else {
  writeFileSync(out, body);
  console.log('wrote ' + entries.length + ' sections');
}
