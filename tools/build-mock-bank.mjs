// Builds interactive/assets/data/mock-bank.js: every interview cheat-sheet question with its answer, for the mock interview page.
// A data file (instead of fetching the lesson pages) keeps the page working when opened straight from disk (file://).
// Usage: node tools/build-mock-bank.mjs [--check]   (--check fails if the file is stale)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../interactive', import.meta.url)));
const out = join(root, 'assets', 'data', 'mock-bank.js');

const bank = [];
for (const f of readdirSync(root).filter((n) => /^\d\d-.*\.html$/.test(n) && !n.endsWith('-quiz.html')).sort()) {
  const html = readFileSync(join(root, f), 'utf8').replace(/\r\n/g, '\n');
  const topic = (html.match(/data-topic="([^"]+)"/) || [])[1];
  const sec = html.match(/<section[^>]*data-title="Interview cheat sheet"[^>]*>([\s\S]*?)<\/section>/);
  if (!topic || !sec) continue;
  let i = 0;
  for (const m of sec[1].matchAll(/<details[^>]*>\s*<summary[^>]*>([\s\S]*?)<\/summary>([\s\S]*?)<\/details>/g)) {
    bank.push({ id: topic + '-' + i, topic, q: m[1].trim(), a: m[2].trim() });
    i++;
  }
}
const body = '/* Generated by tools/build-mock-bank.mjs. Do not edit. */\nCT.mockBank = ' + JSON.stringify(bank) + ';\n';
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== body) { console.error('mock-bank.js is stale: run node tools/build-mock-bank.mjs'); process.exit(1); }
  console.log('mock bank is up to date (' + bank.length + ' questions)');
} else {
  writeFileSync(out, body);
  console.log('wrote ' + bank.length + ' questions');
}
