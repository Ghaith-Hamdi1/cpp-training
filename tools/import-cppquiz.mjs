// Builds interactive/assets/data/puzzles.js from a clone of the CppQuiz.org question repository.
// The questions are by Anders Schau Knatten and contributors, licensed CC BY-SA 4.0 (https://cppquiz.org/quiz/about/).
// Usage: git clone --depth 1 https://github.com/knatten/cppquiz23 <dir>
//        node tools/import-cppquiz.mjs <dir>
// Only questions in state PUB (published on the site) are imported.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node tools/import-cppquiz.mjs <path to a clone of github.com/knatten/cppquiz23>'); process.exit(1); }
const qdir = join(resolve(src), 'questions');
const rd = (f) => (existsSync(f) ? readFileSync(f, 'utf8').replace(/\r\n/g, '\n').replace(/\s+$/, '') : '');

const items = readdirSync(qdir).filter((d) => /^\d+$/.test(d)).map(Number).sort((a, b) => a - b).flatMap((id) => {
  const dir = join(qdir, String(id));
  const meta = JSON.parse(rd(join(dir, 'meta_data.json')));
  if (meta.state !== 'PUB') return [];
  if (!['OK', 'CE', 'UD', 'US'].includes(meta.result)) throw new Error(`question ${id}: unknown result ${meta.result}`);
  return [{ id, d: meta.difficulty, r: meta.result, a: meta.result === 'OK' ? String(meta.answer) : '', code: rd(join(dir, 'question.cpp')), hint: rd(join(dir, 'hint.md')), ex: rd(join(dir, 'explanation.md')) }];
});

const header = `/* C++ Puzzles: questions from CppQuiz.org (https://cppquiz.org), by Anders Schau Knatten and contributors.
 * Licensed under the Creative Commons Attribution-ShareAlike 4.0 International License
 * (https://creativecommons.org/licenses/by-sa/4.0/). Source: https://github.com/knatten/cppquiz23
 * Changes: reformatted into this data file (id d=difficulty r=result a=answer code hint ex=explanation); the text is unchanged.
 * Generated by tools/import-cppquiz.mjs. This file stays under CC BY-SA 4.0. */
`;
const out = header + 'CT.puzzleData = [\n' + items.map((q) => '  ' + JSON.stringify(q)).join(',\n') + '\n];\n';
const dest = join(resolve(fileURLToPath(new URL('..', import.meta.url))), 'interactive', 'assets', 'data', 'puzzles.js');
writeFileSync(dest, out);
console.log(`wrote ${items.length} puzzles (${(out.length / 1024).toFixed(0)} KB)`);
