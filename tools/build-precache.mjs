// Rewrites the generated block of interactive/sw.js: the list of files to precache for offline use
// and a cache name derived from their content, so a changed lesson invalidates old caches.
// Usage: node tools/build-precache.mjs [--check]   (--check fails if sw.js is stale)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../interactive', import.meta.url)));
const swPath = join(root, 'sw.js');
const lf = (s) => s.replace(/\r\n/g, '\n');   // checkouts on Windows may use CRLF; hash and compare LF only

const walk = (d) => readdirSync(d).flatMap((n) => {
  const p = join(d, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const files = walk(root).map((p) => relative(root, p).split(sep).join('/')).filter((f) => f !== 'sw.js').sort();

const hash = createHash('sha1');
for (const f of files) hash.update(f + '\0' + lf(readFileSync(join(root, f), 'utf8')) + '\0');
const version = hash.digest('hex').slice(0, 10);

const block = '/* BEGIN GENERATED by tools/build-precache.mjs: do not edit by hand */\n' +
  `const CACHE = 'cpptrain-${version}';\n` +
  `const PRECACHE = ${JSON.stringify(['./', ...files], null, 2)};\n` +
  '/* END GENERATED */';

const current = lf(readFileSync(swPath, 'utf8'));
const re = /\/\* BEGIN GENERATED[\s\S]*?\/\* END GENERATED \*\//;
if (!re.test(current)) { console.error('sw.js has no BEGIN/END GENERATED markers'); process.exit(1); }
const next = current.replace(re, () => block);

if (process.argv.includes('--check')) {
  if (next !== current) { console.error('sw.js precache list is stale: run node tools/build-precache.mjs'); process.exit(1); }
  console.log(`sw.js precache list is up to date (${files.length + 1} entries, cache cpptrain-${version})`);
} else {
  writeFileSync(swPath, next);
  console.log(`wrote ${files.length + 1} precache entries, cache cpptrain-${version}`);
}
